// palette keys: o outline, L light, d mid, M dark, h handle, q handle dark
function materialPalette(color) {
  const c = parseInt(color.slice(1), 16);
  const r = (c >> 16) & 255, g = (c >> 8) & 255, b = c & 255;
  const sh = (k) => [Math.min(255, r * k), Math.min(255, g * k), Math.min(255, b * k)];
  return { o: sh(0.3), L: sh(1.18), d: sh(0.92), M: sh(0.62), h: [137, 103, 55], q: [92, 66, 34] };
}

