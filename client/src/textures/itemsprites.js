export function drawItemSprite(id, item) {
  if (item && item.tool && T[item.tool.type]) {
    const pal = materialPalette(TOOL_TIERS[item.tool.material].color);
    return drawTemplate(T[item.tool.type], pal);
  }
  if (item && item.armor && !item.armor.glider) {
    const pal = materialPalette(ARMOR_MATS[item.armor.material].color);
    const tpl = T[['helmet', 'chestplate', 'leggings', 'boots'][item.armor.slot]];
    return drawTemplate(tpl, pal);
  }
  const def = SPRITE_DEFS[id];
  if (!def) return null;
  const [name, pal] = def;
  const [tpl, basePal] = SIMPLE[name];
  return drawTemplate(tpl, pal || basePal);
}

// Pixel masks of flat sprites, used for extruded 3D item meshes.
export function spritePixels(canvas) {
  const ctx = canvas.getContext('2d');
  return ctx.getImageData(0, 0, canvas.width, canvas.height);
}
